import { readdir, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDirectory =
  dirname(fileURLToPath(import.meta.url));

const projectRoot =
  join(scriptDirectory, "..");

const articlesDirectory =
  join(
    projectRoot,
    "src",
    "content",
    "articles",
  );

const outputFile =
  join(
    articlesDirectory,
    "articles.generated.ts",
  );

const entries =
  await readdir(
    articlesDirectory,
    {
      withFileTypes: true,
    },
  );

const articleFiles =
  entries
    .filter(
      (entry) =>
        entry.isFile() &&
        entry.name.endsWith(".mdx"),
    )
    .map(
      (entry) =>
        entry.name,
    )
    .sort(
      (a, b) =>
        a.localeCompare(b),
    );

const imports =
  articleFiles
    .map(
      (fileName, index) =>
        `import ArticleContent${index}, { article as articleMetadata${index} } from "./${fileName}";`,
    )
    .join("\n");

const registrations =
  articleFiles
    .map(
      (_, index) =>
`  {
    metadata:
      articleMetadata${index} as unknown as ArticleMetadata,

    content:
      ArticleContent${index} as ComponentType,
  },`,
    )
    .join("\n");

const generatedFile =
`/* ============================================================
   AUTO-GENERATED FILE

   DO NOT EDIT MANUALLY.

   Generated by:
   scripts/generate-articles-registry.mjs
============================================================ */

import type { ComponentType } from "react";

import type { ArticleMetadata } from "@/types/article";

${imports}

/* ============================================================
   TYPES
============================================================ */

export type GeneratedArticle = {
  metadata: ArticleMetadata;
  content: ComponentType;
};

/* ============================================================
   GENERATED ARTICLES
============================================================ */

export const generatedArticles: GeneratedArticle[] = [
${registrations}
];
`;

await writeFile(
  outputFile,
  generatedFile,
  "utf8",
);

console.log(
  `Article registry generated: ${articleFiles.length} article(s).`,
);

for (const articleFile of articleFiles)
{
  console.log(
    ` - ${articleFile}`,
  );
}